import express from 'express';
import crypto from 'node:crypto';
const app = express(); app.use(express.json());
let recursos = new Map([[1, { id: 1, nome: 'Ana', versao: 1 }]]); let proximo = 2; let efeitos = 0;
const etagDe = (o) => '"' + crypto.createHash('sha1').update(JSON.stringify(o)).digest('hex').slice(0, 12) + '"';
app.get('/usuarios/:id', (req, res) => {
  const u = recursos.get(Number(req.params.id)); if (!u) return res.status(404).json({ erro: 'não encontrado' });
  const et = etagDe(u); res.set('ETag', et); res.set('Cache-Control', 'private, max-age=0, must-revalidate');
  if (req.get('If-None-Match') === et) return res.status(304).end();
  if (req.accepts(['json', 'xml']) !== 'json') return res.status(406).json({ erro: 'só application/json' });
  res.json(u);
});
app.post('/usuarios', (req, res) => { const u = { id: proximo++, nome: req.body.nome, versao: 1 }; recursos.set(u.id, u); efeitos++; res.status(201).set('Location', '/usuarios/' + u.id).json(u); });
app.put('/usuarios/:id', (req, res) => {
  const id = Number(req.params.id); const atual = recursos.get(id);
  if (!req.get('If-Match')) return res.status(428).json({ erro: 'If-Match obrigatório' });
  if (atual && req.get('If-Match') !== etagDe(atual)) return res.status(412).json({ erro: 'versão desatualizada' });
  const mudou = !atual || atual.nome !== req.body.nome; const u = mudou ? { id, nome: req.body.nome, versao: (atual?.versao ?? 0) + 1 } : atual; recursos.set(id, u); res.set('ETag', etagDe(u)).json(u);
});
app.delete('/usuarios/:id', (req, res) => { const existia = recursos.delete(Number(req.params.id)); res.status(existia ? 204 : 404).end(); });
app.all('/usuarios/:id', (req, res) => res.status(405).set('Allow', 'GET, PUT, DELETE').json({ erro: 'método não permitido' }));
const srv = await new Promise((ok) => { const s = app.listen(0, '127.0.0.1', () => ok(s)); }); const b = 'http://127.0.0.1:' + srv.address().port;
const f = async (m, p, o = {}) => { const r = await fetch(b + p, { method: m, ...o, headers: { 'content-type': 'application/json', ...(o.headers || {}) }, body: o.body ? JSON.stringify(o.body) : undefined }); const t = await r.text(); return { s: r.status, h: r.headers, t }; };
const lin = (r, hs = []) => r.s + ' ' + (r.t || '(sem corpo)').slice(0, 70) + hs.map((h) => ' | ' + h + ': ' + r.h.get(h)).join('');
console.log('== idempotência dos métodos');
let a = await f('POST', '/usuarios', { body: { nome: 'Bia' } }); let c = await f('POST', '/usuarios', { body: { nome: 'Bia' } });
console.log('POST duas vezes:', lin(a, ['location']), '||', lin(c, ['location']), '| recursos criados:', efeitos);
let g = await f('GET', '/usuarios/1'); const et1 = g.h.get('etag');
console.log('GET:', lin(g, ['etag', 'cache-control']));
console.log('GET com If-None-Match igual:', lin(await f('GET', '/usuarios/1', { headers: { 'if-none-match': et1 } })));
console.log('GET com Accept: application/xml:', lin(await f('GET', '/usuarios/1', { headers: { accept: 'application/xml' } })));
console.log('GET inexistente:', lin(await f('GET', '/usuarios/99')));
console.log('PUT sem If-Match:', lin(await f('PUT', '/usuarios/1', { body: { nome: 'Ana 2' } })));
const p1 = await f('PUT', '/usuarios/1', { body: { nome: 'Ana 2' }, headers: { 'if-match': et1 } });
console.log('PUT com If-Match correto:', lin(p1, ['etag']));
console.log('PUT repetido com o ETag antigo (outro cliente já alterou):', lin(await f('PUT', '/usuarios/1', { body: { nome: 'Ana 3' }, headers: { 'if-match': et1 } })));
const et2 = p1.h.get('etag');
const p2 = await f('PUT', '/usuarios/1', { body: { nome: 'Ana 2' }, headers: { 'if-match': et2 } });
console.log('PUT repetido com o mesmo conteúdo e o ETag atual: versão', JSON.parse(p1.t).versao, '->', JSON.parse(p2.t).versao, '| mesmo ETag:', p1.h.get('etag') === p2.h.get('etag'), '(o estado final é o mesmo: idempotente)');
console.log('DELETE:', lin(await f('DELETE', '/usuarios/2')), '| DELETE de novo:', lin(await f('DELETE', '/usuarios/2')));
console.log('PATCH em recurso (rota não implementada para PATCH):', lin(await f('PATCH', '/usuarios/1', { body: {} }), ['allow']));
